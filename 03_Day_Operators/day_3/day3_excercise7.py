# Declare variables
radius = input("What is the radius of the circle?: ") # The measure in m please:)
pi = 3.14

# Calculate the area
area = pi * (float(radius) ** 2)
print("The area is:", area, "m**2")

# Calculate the circunference
circ = 2 * pi * float(radius)
print("The circunference is:", circ, "m")